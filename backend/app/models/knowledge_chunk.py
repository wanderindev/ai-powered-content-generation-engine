"""Knowledge chunks: the retrieval unit of the RAG knowledge layer (#623, epic #617).

One row is one embeddable piece of text in one language: a section (or part of
a section) of an article body, a single article fact-check claim, or a
verified-claims KB entry (``source_type``, see ``KnowledgeSourceType``). The
chunker (``app/services/knowledge/chunker.py``) produces the article rows; the
indexer (#624) and the claim indexer (#625) write them.

**No visibility is stored here.** Publishing is time-based
(``published_at <= now()``), so a stored "public" flag would go stale with no
write to refresh it; retrieval (#626) joins ``articles`` at query time instead.

``embedding`` (pgvector, HNSW cosine) and ``search_vector`` (generated
``tsvector``, ``english`` / ``spanish`` by row language) are Table columns but
**not ORM attributes** (``exclude_properties``), exactly like the 0041 media
search columns: no entity SELECT, count subquery or INSERT ... RETURNING ever
names them, so only the retrieval / indexer code touches them, through
``KnowledgeChunk.__table__.c``. ``search_vector`` is generated by Postgres
(SQL in ``app/models/search_sql.py``) and never written by the app.
"""

from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Column,
    Computed,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base
from app.models.enums import KnowledgeSourceType, Language, status_check
from app.models.search_sql import KNOWLEDGE_CHUNK_SEARCH_VECTOR_SQL

__all__ = ["EMBEDDING_DIMENSIONS", "KnowledgeChunk", "KnowledgeSourceType"]

# voyage-4 output size (app/services/embeddings.py); the column is fixed-width.
EMBEDDING_DIMENSIONS = 1024


class KnowledgeChunk(Base):
    __tablename__ = "knowledge_chunks"

    id: Mapped[int] = mapped_column(primary_key=True)

    # --- Location -------------------------------------------------------------
    source_type: Mapped[str] = mapped_column(String(20))
    # The id of the row the text came from (article / fact_check_claims /
    # verified_claims, by source_type). Not an FK: it is polymorphic.
    source_id: Mapped[int] = mapped_column(Integer)
    # The article the chunk belongs to (ARTICLE and ARTICLE_CLAIM rows), so an
    # article delete cascades its chunks; NULL for VERIFIED_CLAIM rows.
    article_id: Mapped[int | None] = mapped_column(
        ForeignKey("articles.id", ondelete="CASCADE"), index=True
    )
    language: Mapped[str] = mapped_column(String(2))
    chunk_index: Mapped[int] = mapped_column(Integer)

    # --- Content --------------------------------------------------------------
    # "Heading > Subheading" of the section the chunk came from; NULL for text
    # before the first heading and for claims.
    heading_path: Mapped[str | None] = mapped_column(Text)
    content: Mapped[str] = mapped_column(Text)
    # sha256 hex of the embedding text (title > heading path + content), so the
    # indexer re-embeds only chunks whose embedded text changed.
    content_hash: Mapped[str] = mapped_column(String(64))
    token_count: Mapped[int] = mapped_column(Integer)
    # Model that produced ``embedding``; NULL until the chunk is embedded.
    embedding_model: Mapped[str | None] = mapped_column(String(50))
    # Article chunks: section info; claim chunks: verdict / citation / method.
    meta: Mapped[dict | None] = mapped_column(JSONB)

    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )

    # --- Search columns: on the Table, NOT ORM attributes (see module doc) -----
    embedding = Column("embedding", Vector(EMBEDDING_DIMENSIONS), nullable=True)
    search_vector = Column(
        "search_vector",
        TSVECTOR,
        Computed(KNOWLEDGE_CHUNK_SEARCH_VECTOR_SQL, persisted=True),
    )

    __table_args__ = (
        status_check("knowledge_chunks", "source_type", KnowledgeSourceType),
        status_check("knowledge_chunks", "language", Language),
        UniqueConstraint(
            "source_type",
            "source_id",
            "language",
            "chunk_index",
            name="uq_knowledge_chunks_source_chunk",
        ),
        Index(
            "ix_knowledge_chunks_embedding",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
        Index("ix_knowledge_chunks_search_vector", "search_vector", postgresql_using="gin"),
    )
    __mapper_args__ = {"exclude_properties": ["embedding", "search_vector"]}
