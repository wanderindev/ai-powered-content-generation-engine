"""Research intake: store a finished research document for a suggestion (#641).

One write path, shared by ``POST /admin/dashboard/research/upload`` and the MCP
``submit_research`` tool. It is the in-app form of the ``/research-process``
skill: the same quality checks, run by
``research_common.validate_research_document`` (>= 4,000 words; a Sources /
References / Bibliography / Works Cited / Citations heading, auto-generated by
Haiku from inline citations when missing; >= 2 of the suggestion's sub_topics
covered, judged by Haiku against the ``sub_topics`` stored on the suggestion
rather than the skill's prompt file), then an INSERT of a ``PENDING``
``research`` row or an UPDATE of the existing one.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import UTC, datetime

from sqlalchemy.orm import Session

from app.models.article_suggestion import ArticleSuggestion
from app.models.enums import ContentStatus
from app.models.research import Research
from app.services.research import validate_research_document

# What ``research_common._generate_references_section`` appends to the
# submitted body: a rule, then a section that starts "## References" or
# "## Sources" (any other model reply is discarded there).
_GENERATED_REFS_PREFIXES = ("\n\n---\n\n## References", "\n\n---\n\n## Sources")


class ResearchIntakeError(ValueError):
    """A research submission refused as a whole. Messages never quote the body."""


class SuggestionNotFoundError(ResearchIntakeError):
    pass


class ResearchConflictError(ResearchIntakeError):
    """The suggestion already has research this call may not overwrite."""


@dataclass(frozen=True)
class _SuggestionSnapshot:
    """The suggestion fields intake needs, read before the transaction ends
    (validation makes Haiku calls; no connection is held across them).
    ``validate_research_document`` reads only ``sub_topics``."""

    id: int
    title: str
    sub_topics: list[str]


@dataclass
class ResearchIntakeResult:
    accepted: bool
    # "inserted" | "updated" | "replayed" | "rejected" (failed quality checks)
    action: str
    suggestion_id: int
    suggestion_title: str
    word_count: int
    research_id: int | None = None
    status: str | None = None
    references_generated: bool = False
    checks: dict | None = None

    @property
    def replayed(self) -> bool:
        return self.action == "replayed"


def same_research_body(stored: str | None, submitted: str) -> bool:
    """Whether ``submitted`` is the body already stored (the replay test).

    True when the two are identical after trimming outer whitespace, or when
    the stored body is exactly the submitted one followed by the References /
    Sources section intake compiled for it (``---`` rule, then the heading).
    """
    stored = (stored or "").strip()
    submitted = submitted.strip()
    if not submitted:
        return False
    if stored == submitted:
        return True
    return stored.startswith(submitted) and stored[len(submitted) :].startswith(
        _GENERATED_REFS_PREFIXES
    )


def _load_existing(db: Session, suggestion_id: int) -> Research | None:
    return (
        db.query(Research)
        .filter(Research.suggestion_id == suggestion_id)
        .order_by(Research.id)
        .first()
    )


def _replayed(snapshot: _SuggestionSnapshot, research: Research) -> ResearchIntakeResult:
    return ResearchIntakeResult(
        accepted=True,
        action="replayed",
        suggestion_id=snapshot.id,
        suggestion_title=snapshot.title,
        word_count=len((research.content or "").split()),
        research_id=research.id,
        status=research.status,
    )


def _guard_existing(
    research: Research, *, replace: bool, force: bool, force_available: bool
) -> None:
    if not replace:
        raise ResearchConflictError(
            f"Research {research.id} already exists for this suggestion with a different "
            "body; nothing was changed. Replacing it needs replace=true."
        )
    # Re-uploading over APPROVED research would orphan any articles already
    # generated from the old content (#88).
    if research.status == ContentStatus.APPROVED.value and not force:
        raise ResearchConflictError(
            "Research for this suggestion is already APPROVED. "
            "Re-uploading would orphan generated content. "
            + (
                "Pass force=true to overwrite."
                if force_available
                else "Only the operator can replace it, from the admin research upload."
            )
        )


def submit_research(
    db: Session,
    suggestion_id: int,
    content: str,
    *,
    replace: bool,
    force: bool = False,
    converge_identical: bool,
    force_available: bool = True,
) -> ResearchIntakeResult:
    """Validate a research document and store it as the suggestion's research.

    * Unknown suggestion: :class:`SuggestionNotFoundError`.
    * With ``converge_identical`` (the MCP tool), research that already has
      **the same body** (:func:`same_research_body`) is returned unchanged
      with ``action="replayed"`` (#495): nothing is validated or written, and
      its status is left alone.
    * Otherwise existing research is :class:`ResearchConflictError` unless
      ``replace``; an APPROVED one also needs ``force``. Both are checked
      before validation, so a refused call spends no Haiku tokens.
    * Failed quality checks: ``accepted=False``, ``action="rejected"``, and
      ``checks`` says which failed; nothing is written.
    * Otherwise INSERT a PENDING row, or UPDATE the existing one and reset it
      to PENDING (changed content must re-enter review). Commits.

    The two callers differ only in these flags:

    * ``POST /admin/dashboard/research/upload``: ``replace=True``, its
      ``force``, ``converge_identical=False``. That is its pre-#641 behaviour
      exactly: APPROVED is a 409 without ``force`` even for the same file, and
      any accepted re-upload, identical or not, is re-validated, rewritten
      and reset to PENDING (re-uploading a REJECTED document sends it back to
      review).
    * MCP ``submit_research``: the agent's ``replace``, never ``force``
      (``force_available=False`` words the APPROVED conflict accordingly),
      ``converge_identical=True``. So an agent cannot overwrite APPROVED
      research, and a retried submit converges instead of erroring.

    Connection pool: the transaction is ended before validation (which calls
    Haiku) and a new one starts for the write, where the existing-row checks
    run again in case a concurrent call won the race. Nothing else is
    triggered, on either path: research is not in the knowledge index, its
    fact check is kicked off from the admin grid, and the driver's
    ``WAIT_RESEARCH_READY`` gate polls on its own.
    """
    suggestion = db.query(ArticleSuggestion).filter(ArticleSuggestion.id == suggestion_id).first()
    if suggestion is None:
        raise SuggestionNotFoundError("Suggestion not found")
    snapshot = _SuggestionSnapshot(
        id=suggestion.id,
        title=suggestion.title,
        sub_topics=list(suggestion.sub_topics or []),
    )

    existing = _load_existing(db, snapshot.id)
    if existing is not None:
        if converge_identical and same_research_body(existing.content, content):
            return _replayed(snapshot, existing)
        _guard_existing(existing, replace=replace, force=force, force_available=force_available)
    db.commit()  # end the read transaction: no connection held across Haiku

    validation = validate_research_document(content, snapshot)
    if not validation["valid"]:
        return ResearchIntakeResult(
            accepted=False,
            action="rejected",
            suggestion_id=snapshot.id,
            suggestion_title=snapshot.title,
            word_count=validation["word_count"],
            checks=validation["checks"],
        )
    final_content = validation["content"]

    now = datetime.now(UTC)
    existing = _load_existing(db, snapshot.id)
    if existing is not None:
        if converge_identical and same_research_body(existing.content, content):
            return _replayed(snapshot, existing)
        _guard_existing(existing, replace=replace, force=force, force_available=force_available)
        existing.content = final_content
        existing.status = ContentStatus.PENDING.value  # content changed: re-enter review
        existing.updated_at = now
        research, action = existing, "updated"
    else:
        research = Research(
            suggestion_id=snapshot.id,
            content=final_content,
            status=ContentStatus.PENDING.value,
            created_at=now,
            updated_at=now,
        )
        db.add(research)
        action = "inserted"
    db.commit()
    db.refresh(research)
    return ResearchIntakeResult(
        accepted=True,
        action=action,
        suggestion_id=snapshot.id,
        suggestion_title=snapshot.title,
        word_count=validation["word_count"],
        research_id=research.id,
        status=research.status,
        references_generated=final_content != content,
        checks=validation["checks"],
    )
